#![forbid(unsafe_code)]

/// Map an ASN.1 OID string to a canonical algorithm name matching `ALGORITHM_CATALOG`.
///
/// Sources: RFC 3279, RFC 4055, RFC 5480, RFC 8410, NIST FIPS 203/204/205, X.509 specs.
pub fn oid_to_algorithm(oid: &str) -> Option<&'static str> {
    match oid {
        // ── RSA ───────────────────────────────────────────────────────────────
        "1.2.840.113549.1.1.1" => Some("RSA"),
        "1.2.840.113549.1.1.5" => Some("SHA-1"),   // sha1WithRSAEncryption (sig algo)
        "1.2.840.113549.1.1.11" => Some("SHA-256"), // sha256WithRSAEncryption
        "1.2.840.113549.1.1.12" => Some("SHA-384"), // sha384WithRSAEncryption
        "1.2.840.113549.1.1.13" => Some("SHA-512"), // sha512WithRSAEncryption

        // ── DSA ───────────────────────────────────────────────────────────────
        "1.2.840.10040.4.1" => Some("DSA"),
        "1.2.840.10040.4.3" => Some("DSA"), // dsaWithSHA1

        // ── EC / ECDSA ────────────────────────────────────────────────────────
        "1.2.840.10045.2.1" => Some("ECDSA"),
        "1.2.840.10045.4.3.1" => Some("ECDSA-P-256"), // ecdsa-with-SHA224
        "1.2.840.10045.4.3.2" => Some("ECDSA-P-256"), // ecdsa-with-SHA256
        "1.2.840.10045.4.3.3" => Some("ECDSA-P-384"), // ecdsa-with-SHA384
        "1.2.840.10045.4.3.4" => Some("ECDSA-P-521"), // ecdsa-with-SHA512

        // ── Named curves ──────────────────────────────────────────────────────
        "1.2.840.10045.3.1.7" => Some("ECDSA-P-256"),  // prime256v1 / secp256r1
        "1.3.132.0.34" => Some("ECDSA-P-384"),          // secp384r1
        "1.3.132.0.35" => Some("ECDSA-P-521"),          // secp521r1
        "1.3.101.110" => Some("X25519"),                 // id-X25519 (RFC 8410)
        "1.3.101.111" => Some("X448"),
        "1.3.101.112" => Some("Ed25519"),
        "1.3.101.113" => Some("Ed448"),

        // ── DH ────────────────────────────────────────────────────────────────
        "1.2.840.10046.2.1" => Some("DH-2048"),

        // ── Symmetric (AES) ───────────────────────────────────────────────────
        "2.16.840.1.101.3.4.1.1" => Some("AES-128"),  // AES-128-ECB
        "2.16.840.1.101.3.4.1.2" => Some("AES-128"),  // AES-128-CBC
        "2.16.840.1.101.3.4.1.6" => Some("AES-128"),  // AES-128-GCM
        "2.16.840.1.101.3.4.1.21" => Some("AES-192"), // AES-192-CBC
        "2.16.840.1.101.3.4.1.26" => Some("AES-192"), // AES-192-GCM
        "2.16.840.1.101.3.4.1.41" => Some("AES-256"), // AES-256-CBC
        "2.16.840.1.101.3.4.1.42" => Some("AES-256"), // AES-256-CBC (SMIME)
        "2.16.840.1.101.3.4.1.46" => Some("AES-256"), // AES-256-GCM

        // ── 3DES ──────────────────────────────────────────────────────────────
        "1.2.840.113549.3.7" => Some("3DES"),
        "1.3.14.3.2.7" => Some("DES"),

        // ── Hash ─────────────────────────────────────────────────────────────
        "1.3.14.3.2.26" => Some("SHA-1"),
        "2.16.840.1.101.3.4.2.1" => Some("SHA-256"),
        "2.16.840.1.101.3.4.2.2" => Some("SHA-384"),
        "2.16.840.1.101.3.4.2.3" => Some("SHA-512"),
        "2.16.840.1.101.3.4.2.8" => Some("SHA3-256"),
        "2.16.840.1.101.3.4.2.10" => Some("SHA3-512"),
        "1.2.840.113549.2.5" => Some("MD5"),

        // ── Post-quantum (NIST FIPS 203/204/205 — OIDs pending full standardization) ──
        // Draft OIDs per IETF draft-ietf-lamps-pq-composite-kem
        "2.16.840.1.101.3.4.4.1" => Some("ML-KEM-512"),
        "2.16.840.1.101.3.4.4.2" => Some("ML-KEM-768"),
        "2.16.840.1.101.3.4.4.3" => Some("ML-KEM-1024"),
        "2.16.840.1.101.3.4.3.17" => Some("ML-DSA-44"),
        "2.16.840.1.101.3.4.3.18" => Some("ML-DSA-65"),
        "2.16.840.1.101.3.4.3.19" => Some("ML-DSA-87"),

        _ => None,
    }
}
